def environment() -> c.EnvironmentIdentity:
    cluster = c.ClusterIdentity("1234567890123456789", 160004)
    return c.EnvironmentIdentity(
        "g4-offline-fixture",
        c.VMGeneration(901, "11111111-1111-4111-8111-111111111111", "a" * 64),
        cluster,
        c.DatabaseIdentity(cluster, "g4_fixture", 17001),
    )


def run() -> c.RunIdentity:
    return c.RunIdentity(environment(), "22222222-2222-4222-8222-222222222222")


def credential(purpose: c.Purpose) -> c.CredentialIdentity:
    # Separate literal role/reference names; no secret values or secret access.
    role, reference = {
        c.Purpose.RUNTIME: ("fixture_runtime", "runtime_reference"),
        c.Purpose.VERIFIER: ("fixture_verifier", "verifier_reference"),
        c.Purpose.MIGRATOR: ("fixture_migrator", "migrator_reference"),
        c.Purpose.ADMIN: ("fixture_admin", "admin_reference"),
    }[purpose]
    return c.CredentialIdentity(environment(), purpose, role, reference, "fixture_issuer")


def session(purpose: c.Purpose, pid: int) -> c.SessionIdentity:
    identity = credential(purpose)
    return c.SessionIdentity(run(), identity, purpose, identity.role, identity.role, pid, 1000000)


def request(target: str = "g4-offline-fixture") -> c.ExecutionRequest:
    return c.ExecutionRequest(run(), target, c.Purpose.RUNTIME)


def claimed_authorization() -> c.AuthorizedExecutionRequest:
    candidate = c.ApprovalCandidate(environment(), "b" * 64)
    reference = c.ExternalApprovalReference(candidate, "fixture_approval", "fixture_issuer")
    return c.AuthorizedExecutionRequest(request(), c.ApprovedContract(candidate, reference))


@dataclass
class ForbiddenOperations:
    """Record every attempted boundary crossing and fail without doing any work."""

    attempts: list[str] = field(default_factory=list)

    def reject(self, operation: str) -> None:
        self.attempts.append(operation)
        raise AssertionError("Forbidden external operation")

    def credentials(self) -> None:
        self.reject("credentials")

    def connect(self) -> None:
        self.reject("connect")

    def process(self) -> None:
        self.reject("process")

    def auth03(self) -> None:
        self.reject("auth03")


